-- chieu schema hoac dung khi dung mot Supabase project moi hoan toan.

create table if not exists posts (
    id bigint generated by default as identity primary key,
    title text not null,
    content text not null,
    image_url text,
    platforms text not null, -- vd: 'facebook,linkedin,wordpress'
    status text not null default 'draft', -- draft | posted | failed | partial: ok=... fail=...
    scheduled_time timestamptz, -- null = dang ngay khi workflow chay
    posted_at timestamptz,
    error_message text,
    created_at timestamptz not null default now(),
    created_by text default '',
    priority text default 'medium',
    approved_by text default '',
    approved_at timestamptz,
    content_social text, -- noi dung rieng cho WordPress neu khac content (vd: content dung cho FB/LinkedIn)
    wp_category_ids text, -- category id tren WordPress, dang chuoi phan cach dau phay vd '1,5,9'
    comment_text text
);

create index if not exists posts_status_scheduled_time_idx
    on posts (status, scheduled_time);

-- Bang `users` cho dang nhap dashboard (CHUA TON TAI - can tao moi).
create table if not exists users (
    id uuid primary key default gen_random_uuid(),
    email text not null unique,
    password_hash text not null,
    display_name text not null default '',
    role text not null default 'member', -- admin | member
    created_at timestamptz not null default now()
);

